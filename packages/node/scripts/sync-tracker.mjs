// Copies the WordPress plugin's assets/tracker.js into this package, so both
// ship the same tracker. Runs before tests and before every publish.
//
//   dist/tracker.js         the file as-is, served by npm CDNs (jsDelivr, unpkg)
//   dist/tracker-source.js  the same source as a string, for trackerScripts()

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '..', '..', '..', 'assets', 'tracker.js');
const dist = join(here, '..', 'dist');

const code = readFileSync(source, 'utf8');
mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, 'tracker.js'), code);
writeFileSync(
  join(dist, 'tracker-source.js'),
  '// Generated by scripts/sync-tracker.mjs from assets/tracker.js. Do not edit.\n' +
    `export default ${JSON.stringify(code)};\n`,
);
console.log(`Synced tracker.js (${code.length} bytes) into dist/.`);
